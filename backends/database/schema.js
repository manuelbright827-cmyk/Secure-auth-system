async function ensureSchema() {
    const statements = db.dialect === 'postgres' ? postgresSchema : sqliteSchema;
    for (const statement of statements) await db.query(statement);
    if (db.dialect === 'postgres') {
        await db.query("ALTER TABLE users DROP CONSTRAINT IF EXISTS users_role_check");
        await db.query("ALTER TABLE users ADD CONSTRAINT users_role_check CHECK (role IN ('inputer','pharmacist','cashier','manager','admin','administrator'))");
    } else {
        const roleSchema = await db.query("SELECT sql FROM sqlite_master WHERE type='table' AND name='users'");
        if (/role IN \('inputer',\s*'manager',\s*'admin',\s*'administrator'\)/.test(roleSchema.rows[0]?.sql || '')) {
            await db.query('PRAGMA foreign_keys = OFF');
            try {
                const rebuildUsers = db.transaction(async () => {
                    await db.query(`CREATE TABLE users_role_migration (
                        id INTEGER PRIMARY KEY AUTOINCREMENT,
                        email TEXT NOT NULL UNIQUE,
                        password_hash TEXT NOT NULL,
                        role TEXT NOT NULL CHECK (role IN ('inputer','pharmacist','cashier','manager','admin','administrator')),
                        two_factor_secret TEXT,
                        two_factor_enabled INTEGER NOT NULL DEFAULT 0,
                        is_active INTEGER NOT NULL DEFAULT 1,
                        created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
                        updated_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
                    )`);
                    await db.query(`INSERT INTO users_role_migration (id,email,password_hash,role,two_factor_secret,two_factor_enabled,is_active,created_at,updated_at)
                        SELECT id,email,password_hash,role,two_factor_secret,two_factor_enabled,is_active,created_at,updated_at FROM users`);
                    await db.query('DROP TABLE users');
                    await db.query('ALTER TABLE users_role_migration RENAME TO users');
                });
                await rebuildUsers();
            } finally {
                await db.query('PRAGMA foreign_keys = ON');
            }
        }
    }
    for (const statement of db.dialect === 'postgres' ? pharmacyPostgresSchema : pharmacySqliteSchema) await db.query(statement);
    const auditColumns = db.dialect === 'postgres'
        ? ["ALTER TABLE audit_logs ADD COLUMN IF NOT EXISTS actor_role TEXT", "ALTER TABLE audit_logs ADD COLUMN IF NOT EXISTS resource TEXT", "ALTER TABLE audit_logs ADD COLUMN IF NOT EXISTS result TEXT NOT NULL DEFAULT 'success'"]
        : ["ALTER TABLE audit_logs ADD COLUMN actor_role TEXT", "ALTER TABLE audit_logs ADD COLUMN resource TEXT", "ALTER TABLE audit_logs ADD COLUMN result TEXT NOT NULL DEFAULT 'success'"];
    if (db.dialect === 'postgres') {
        for (const statement of auditColumns) await db.query(statement);
    } else {
        const columns = await db.query('PRAGMA table_info(audit_logs)');
        const existing = new Set(columns.rows.map((column) => column.name));
        for (const statement of auditColumns) {
            const name = statement.match(/ADD COLUMN (\w+)/)[1];
            if (!existing.has(name)) await db.query(statement);
        }
    }
}

